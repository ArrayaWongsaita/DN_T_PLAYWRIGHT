import { test, expect } from "@playwright/test";

// ================================================
// บทที่ 09: รายงานผลและ Trace Viewer
// ฝึก: pnpm report (show-report), test.use({ trace }), Trace Viewer
//
// หลังรัน test ทุกครั้ง Playwright สร้างรายงาน HTML ไว้ในโฟลเดอร์ playwright-report/
//   pnpm report            เปิดรายงานในเบราว์เซอร์ (มันคือ playwright show-report)
//
// Trace คือ "วิดีโอย้อนหลังที่คลิกดูได้" ของ test: ภาพหน้าเว็บทุกขั้น, network, console
//   test.use({ trace: "on" });          เก็บ trace ทุก test (ปกติ config เก็บเฉพาะตอน test ล้ม)
//   pnpm exec playwright show-trace test-results/<ชื่อโฟลเดอร์>/trace.zip   เปิด Trace Viewer
//   (ในรายงาน HTML กดเข้าไปที่ test ก็เห็นปุ่ม trace ได้เหมือนกัน)
//
// ตอน test ล้ม ให้เปิด trace ดูก่อนเสมอ จะเห็นว่าหน้าเว็บหน้าตาเป็นอย่างไรตอนที่พัง
// ================================================

test.use({ trace: "on" });

test.beforeEach(async ({ page }) => {
  await page.goto("/lessons/09-report-and-trace");
});


// ------------------------------------------------
// ข้อ 1: กดปุ่ม "โหลด" แล้วต้องเห็น "พร้อมแล้ว"
// แนวทาง: เขียนแล้วรัน แล้วเปิดรายงานด้วย pnpm report ลองกดเข้า test ดู trace
// ------------------------------------------------
test.fixme("กด โหลด แล้วต้องเห็น พร้อมแล้ว", async ({ page }) => {});
// 👉 เขียน test ของข้อ 1 ตรงนี้


// ------------------------------------------------
// ข้อ 2: ก่อนกดปุ่ม ต้องยังไม่เห็น "พร้อมแล้ว" (toBeHidden)
// แนวทาง: ลอง "ทำให้ test พังโดยตั้งใจ" เช่นเปลี่ยนเป็น toBeVisible()
//         รันแล้วเปิด pnpm report ดูว่า error บอกอะไร และดูภาพหน้าจอตอนพัง
//         เสร็จแล้วเปลี่ยนกลับให้ผ่าน
// ------------------------------------------------
